#!/usr/bin/env bun
// scripts/sync-skills.ts
//
// Bundles the SKILL.md files from github.com/reoclo/skills into
// src/mcp/tools/guides-content.ts, which the MCP server serves as guides
// (list_guides, get_guide and one prompt per skill). The hosted MCP vendors
// src/mcp/tools, so it serves the same text after its next sync.
//
//   bun run skills:sync [path-to-skills-checkout]   regenerate the file
//   bun run skills:check                             exit 1 when it lags reoclo/skills main
//
// Without a path it clones reoclo/skills main shallowly. The check compares
// the guide text only (not the recorded commit), and passes with a note when
// the clone fails, so a network hiccup never blocks CI.

import { existsSync, mkdtempSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { load } from "js-yaml";

const OUT = resolve(import.meta.dir, "..", "src", "mcp", "tools", "guides-content.ts");
const REPO = "https://github.com/reoclo/skills.git";

const args = process.argv.slice(2);
const check = args.includes("--check");
let dir = args.find((a) => !a.startsWith("--"));

if (!dir) {
  dir = join(mkdtempSync(join(tmpdir(), "reoclo-skills-")), "skills");
  const clone = Bun.spawnSync(["git", "clone", "-q", "--depth", "1", REPO, dir]);
  if (clone.exitCode !== 0) {
    const reason = `could not clone ${REPO}: ${clone.stderr.toString().trim()}`;
    if (check) {
      console.log(`skills:check skipped, ${reason}`);
      process.exit(0);
    }
    console.error(reason);
    process.exit(1);
  }
}

const sha = Bun.spawnSync(["git", "-C", dir, "rev-parse", "HEAD"]).stdout.toString().trim();

interface Guide {
  name: string;
  description: string;
  body: string;
}

const guides: Guide[] = [];
const skillDirs = readdirSync(dir, { withFileTypes: true })
  .filter((e) => e.isDirectory() && !e.name.startsWith("."))
  .map((e) => e.name)
  .sort();
for (const name of skillDirs) {
  const file = join(dir, name, "SKILL.md");
  if (!existsSync(file)) continue;
  const text = readFileSync(file, "utf8");
  const match = /^---\n([\s\S]*?)\n---\n/.exec(text);
  const frontmatter = match?.[1];
  if (!match || frontmatter === undefined) throw new Error(`${file}: missing YAML frontmatter`);
  const fm = load(frontmatter) as { name?: unknown; description?: unknown };
  if (typeof fm.name !== "string" || typeof fm.description !== "string") {
    throw new Error(`${file}: frontmatter needs a name and a description`);
  }
  guides.push({
    name: fm.name,
    description: fm.description.trim(),
    body: `${text.slice(match[0].length).trim()}\n`,
  });
}
if (guides.length === 0) throw new Error(`no */SKILL.md files under ${dir}`);

function render(sourceSha: string): string {
  return `// src/mcp/tools/guides-content.ts
// Generated by scripts/sync-skills.ts from github.com/reoclo/skills. Do not edit:
// change the skill there, then run \`bun run skills:sync\`.

export const GUIDES_SOURCE_SHA = ${JSON.stringify(sourceSha)};

export interface GuideContent {
  name: string;
  description: string;
  body: string;
}

export const GUIDES: readonly GuideContent[] = ${JSON.stringify(guides, null, 2)};
`;
}

const withoutSha = (s: string): string => s.replace(/^export const GUIDES_SOURCE_SHA = .*$/m, "");

if (check) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (withoutSha(current) !== withoutSha(render(sha))) {
    console.error(
      `src/mcp/tools/guides-content.ts is behind reoclo/skills main (${sha.slice(0, 7)}). ` +
        "Run `bun run skills:sync` and commit the result.",
    );
    process.exit(1);
  }
  console.log(`skills:check OK, guides match reoclo/skills @ ${sha.slice(0, 7)}`);
} else {
  writeFileSync(OUT, render(sha));
  console.log(`wrote ${guides.length} guides from reoclo/skills @ ${sha}`);
}
